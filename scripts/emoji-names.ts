// Writes src/utils/emoji-all.ts: every emoji with its official Unicode (CLDR) name, from the emojibase-data
// dev dependency, so the `#` field and the tag tray find ANY emoji by name without a runtime dependency or a
// network call. Run `npm run emoji` after updating emojibase-data; the output is committed.
//
// Left out: the PARTS that aren't emoji on their own (skin tones, hair, the flag letters), any emoji that
// can't be an Obsidian tag (keycaps, ℹ️, the subdivision flags: utils/tags.ts decides), and emoji newer than
// NEWEST — no system font draws a brand-new emoji for months, and an offered emoji must not be an empty box.
// Raise NEWEST once a year's emoji have reached macOS, iOS and Windows.
import { readFileSync, writeFileSync } from 'node:fs';
import { cleanTag, isEmojiTag } from '../src/utils/tags.ts';

const NEWEST = 17;
const COMPONENT_GROUP = 2;

interface Emoji { emoji: string; label: string; group?: number; version: number; order?: number }

const data = JSON.parse(readFileSync('node_modules/emojibase-data/en/data.json', 'utf8')) as Emoji[];
const kept = data
  .filter(e => e.group !== undefined && e.group !== COMPONENT_GROUP && e.version <= NEWEST)
  .filter(e => cleanTag(e.emoji) === e.emoji && isEmojiTag(e.emoji))
  .sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
const lines = kept.map(e => `${e.emoji}\t${e.label.toLowerCase()}`).join('\n');
const pkg = JSON.parse(readFileSync('node_modules/emojibase-data/package.json', 'utf8')) as { version: string };

writeFileSync('src/utils/emoji-all.ts',
  `// GENERATED by scripts/emoji-names.ts from emojibase-data ${pkg.version} (MIT) — do not edit; run \`npm run emoji\`.\n` +
  `// ${kept.length} emoji up to Emoji ${NEWEST}, in Unicode's order, one per line: the emoji, a tab, its official name.\n` +
  `export const ALL_EMOJI = ${JSON.stringify(lines)};\n`);
console.log(`src/utils/emoji-all.ts: ${kept.length} emoji`);
